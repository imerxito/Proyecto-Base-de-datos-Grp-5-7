-- 001: tablas sin dependencias (catalogos, proveedores, cajas, usuarios).
-- Todas las tablas conservan sus columnas, tipos y nombres de la Entrega 1,
-- salvo los cambios marcados con [CAMBIO Ax] (ver docs/CAMBIOS_Y_JUSTIFICACION.md).
BEGIN;

CREATE TABLE public.unidad_medida (
  id_unidad   integer GENERATED BY DEFAULT AS IDENTITY,          -- [CAMBIO A3] antes: serial
  nombre      character varying NOT NULL UNIQUE,
  abreviatura character varying NOT NULL UNIQUE,
  descripcion character varying,
  activo      boolean NOT NULL DEFAULT true,
  CONSTRAINT unidad_medida_pkey PRIMARY KEY (id_unidad)
);

CREATE TABLE public.categoria (
  id_categoria integer GENERATED BY DEFAULT AS IDENTITY,         -- [CAMBIO A3]
  nombre       character varying NOT NULL UNIQUE,
  descripcion  character varying,
  activo       boolean NOT NULL DEFAULT true,
  CONSTRAINT categoria_pkey PRIMARY KEY (id_categoria)
);

CREATE TABLE public.proveedor (
  id_proveedor integer GENERATED BY DEFAULT AS IDENTITY,         -- [CAMBIO A3]
  documento    character varying NOT NULL UNIQUE,
  nombre       character varying NOT NULL,
  telefono     character varying,
  correo       character varying,
  direccion    character varying,
  activo       boolean NOT NULL DEFAULT true,
  CONSTRAINT proveedor_pkey PRIMARY KEY (id_proveedor),
  CONSTRAINT proveedor_correo_check CHECK (correo IS NULL OR correo ~ '^[^@\s]+@[^@\s]+$')  -- restriccion nueva
);

CREATE TABLE public.seccion (
  id_seccion integer GENERATED BY DEFAULT AS IDENTITY,           -- [CAMBIO A3]
  nombre     character varying NOT NULL UNIQUE,
  CONSTRAINT seccion_pkey PRIMARY KEY (id_seccion)
);

CREATE TABLE public.caja (
  id_caja integer GENERATED BY DEFAULT AS IDENTITY,              -- [CAMBIO A3]
  nombre  character varying NOT NULL,                            -- [CAMBIO A2] antes: nullable
  activo  boolean NOT NULL DEFAULT true,                         -- [CAMBIO A2] antes: nullable
  CONSTRAINT caja_pkey PRIMARY KEY (id_caja)
);

CREATE TABLE public.usuario (
  id_usuario   integer GENERATED BY DEFAULT AS IDENTITY,         -- [CAMBIO A3]
  auth_id      uuid NOT NULL UNIQUE,   -- FK a auth.users: ver 006_supabase_opcional.sql [CAMBIO A4]
  nombre       character varying NOT NULL,
  cedula       character varying NOT NULL UNIQUE,
  telefono     character varying,
  correo       character varying NOT NULL UNIQUE,
  rol          character varying NOT NULL DEFAULT 'Caja',        -- [CAMBIO A1] antes: default con comillas mal escapadas
  fecha_inicio timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
  activo       boolean NOT NULL DEFAULT true,
  CONSTRAINT usuario_pkey PRIMARY KEY (id_usuario),
  CONSTRAINT usuario_rol_check CHECK (rol IN ('Administrador','Caja','Mesero','Cocina')),    -- restriccion nueva
  CONSTRAINT usuario_correo_check CHECK (correo ~ '^[^@\s]+@[^@\s]+$')                       -- restriccion nueva
);

COMMIT;
