-- 002: ingredientes, productos, recetas y compras. Columnas sin cambios.
-- Politicas de borrado: CASCADE solo cuando el hijo no tiene sentido sin el padre
-- (lineas de detalle, receta); RESTRICT en todo lo demas.
BEGIN;

CREATE TABLE public.ingrediente (
  id_ingrediente    integer GENERATED BY DEFAULT AS IDENTITY,
  codigo            character varying NOT NULL UNIQUE,
  nombre            character varying NOT NULL,
  id_unidad         integer NOT NULL,
  stock             numeric NOT NULL DEFAULT 0 CHECK (stock >= 0::numeric),
  stock_minimo      numeric NOT NULL DEFAULT 0 CHECK (stock_minimo >= 0::numeric),
  precio_referencia numeric NOT NULL DEFAULT 0 CHECK (precio_referencia >= 0::numeric),
  activo            boolean NOT NULL DEFAULT true,
  CONSTRAINT ingrediente_pkey PRIMARY KEY (id_ingrediente),
  CONSTRAINT ingrediente_id_unidad_fkey FOREIGN KEY (id_unidad)
    REFERENCES public.unidad_medida(id_unidad) ON DELETE RESTRICT
);

CREATE TABLE public.producto (
  id_producto  integer GENERATED BY DEFAULT AS IDENTITY,
  codigo       character varying NOT NULL UNIQUE,
  nombre       character varying NOT NULL,
  id_categoria integer NOT NULL,
  precio_venta numeric NOT NULL CHECK (precio_venta >= 0::numeric),
  descripcion  character varying,
  activo       boolean NOT NULL DEFAULT true,
  CONSTRAINT producto_pkey PRIMARY KEY (id_producto),
  CONSTRAINT producto_id_categoria_fkey FOREIGN KEY (id_categoria)
    REFERENCES public.categoria(id_categoria) ON DELETE RESTRICT
);

CREATE TABLE public.receta (
  id_producto    integer NOT NULL,
  id_ingrediente integer NOT NULL,
  cantidad       numeric NOT NULL CHECK (cantidad > 0::numeric),
  CONSTRAINT receta_pkey PRIMARY KEY (id_producto, id_ingrediente),
  CONSTRAINT receta_id_producto_fkey FOREIGN KEY (id_producto)
    REFERENCES public.producto(id_producto) ON DELETE CASCADE,
  CONSTRAINT receta_id_ingrediente_fkey FOREIGN KEY (id_ingrediente)
    REFERENCES public.ingrediente(id_ingrediente) ON DELETE RESTRICT
);

CREATE TABLE public.compra (
  id_compra    integer GENERATED BY DEFAULT AS IDENTITY,
  id_proveedor integer NOT NULL,
  fecha        timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
  estado       character varying NOT NULL DEFAULT 'REGISTRADA'
               CHECK (estado::text = ANY (ARRAY['REGISTRADA','RECIBIDA','ANULADA']::text[])),
  total        numeric NOT NULL DEFAULT 0 CHECK (total >= 0::numeric),
  CONSTRAINT compra_pkey PRIMARY KEY (id_compra),
  CONSTRAINT compra_id_proveedor_fkey FOREIGN KEY (id_proveedor)
    REFERENCES public.proveedor(id_proveedor) ON DELETE RESTRICT
);

CREATE TABLE public.detalle_compra (
  id_compra       integer NOT NULL,
  id_ingrediente  integer NOT NULL,
  cantidad        numeric NOT NULL CHECK (cantidad > 0::numeric),
  precio_aplicado numeric NOT NULL CHECK (precio_aplicado >= 0::numeric),
  CONSTRAINT detalle_compra_pkey PRIMARY KEY (id_compra, id_ingrediente),
  CONSTRAINT detalle_compra_id_compra_fkey FOREIGN KEY (id_compra)
    REFERENCES public.compra(id_compra) ON DELETE CASCADE,
  CONSTRAINT detalle_compra_id_ingrediente_fkey FOREIGN KEY (id_ingrediente)
    REFERENCES public.ingrediente(id_ingrediente) ON DELETE RESTRICT
);

CREATE TABLE public.movimiento_inventario (
  id_movimiento  integer GENERATED BY DEFAULT AS IDENTITY,
  id_ingrediente integer NOT NULL,
  tipo           character varying NOT NULL
                 CHECK (tipo::text = ANY (ARRAY['ENTRADA','SALIDA','AJUSTE']::text[])),
  cantidad       numeric NOT NULL CHECK (cantidad > 0::numeric),
  fecha          timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
  motivo         character varying NOT NULL,
  CONSTRAINT movimiento_inventario_pkey PRIMARY KEY (id_movimiento),
  CONSTRAINT movimiento_inventario_id_ingrediente_fkey FOREIGN KEY (id_ingrediente)
    REFERENCES public.ingrediente(id_ingrediente) ON DELETE RESTRICT
);

COMMIT;
