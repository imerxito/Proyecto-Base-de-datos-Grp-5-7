-- 003: mesas, comandas, facturas, turnos y caja. Columnas sin cambios.
-- Lo nuevo son CHECK de dominio, CHECK de coherencia, politicas ON DELETE
-- y un indice unico parcial (un solo turno abierto por caja).
BEGIN;

CREATE TABLE public.mesa (
  id_mesa    integer GENERATED BY DEFAULT AS IDENTITY,
  numero     integer NOT NULL UNIQUE,
  estado     character varying NOT NULL DEFAULT 'Libre',
  id_seccion integer NOT NULL,
  id_usuario integer,
  CONSTRAINT mesa_pkey PRIMARY KEY (id_mesa),
  CONSTRAINT mesa_estado_check CHECK (estado IN ('Libre','Ocupada','Reservada','Por pagar')),
  CONSTRAINT mesa_id_seccion_fkey FOREIGN KEY (id_seccion)
    REFERENCES public.seccion(id_seccion) ON DELETE RESTRICT,
  CONSTRAINT mesa_id_usuario_fkey FOREIGN KEY (id_usuario)
    REFERENCES public.usuario(id_usuario) ON DELETE SET NULL
);

CREATE TABLE public.comanda (
  id_comanda     integer GENERATED BY DEFAULT AS IDENTITY,
  id_mesa        integer,
  id_usuario     integer,
  estado         character varying NOT NULL DEFAULT 'Abierto',
  observacion    character varying,
  fecha_creacion timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT comanda_pkey PRIMARY KEY (id_comanda),
  CONSTRAINT comanda_estado_check CHECK (estado IN ('Abierto','Enviado','Servido','Cerrado','Anulado')),
  CONSTRAINT comanda_id_mesa_fkey FOREIGN KEY (id_mesa)
    REFERENCES public.mesa(id_mesa) ON DELETE RESTRICT,
  CONSTRAINT comanda_id_usuario_fkey FOREIGN KEY (id_usuario)
    REFERENCES public.usuario(id_usuario) ON DELETE RESTRICT
);

CREATE TABLE public.detalle_comanda (
  id_detalle_comanda integer GENERATED BY DEFAULT AS IDENTITY,
  id_comanda  integer NOT NULL,
  id_producto integer NOT NULL,
  cantidad    integer NOT NULL CHECK (cantidad > 0),
  nota        character varying,
  CONSTRAINT detalle_comanda_pkey PRIMARY KEY (id_detalle_comanda),
  CONSTRAINT detalle_comanda_id_comanda_fkey FOREIGN KEY (id_comanda)
    REFERENCES public.comanda(id_comanda) ON DELETE CASCADE,
  CONSTRAINT detalle_comanda_id_producto_fkey FOREIGN KEY (id_producto)
    REFERENCES public.producto(id_producto) ON DELETE RESTRICT
);

CREATE TABLE public.factura (
  id_factura    integer GENERATED BY DEFAULT AS IDENTITY,
  id_mesa       integer NOT NULL,
  id_usuario    integer NOT NULL,
  fecha_emision timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
  subtotal      numeric NOT NULL DEFAULT 0 CHECK (subtotal >= 0::numeric),
  propina       numeric NOT NULL DEFAULT 0 CHECK (propina >= 0::numeric),
  total_pagar   numeric NOT NULL DEFAULT 0 CHECK (total_pagar >= 0::numeric),
  CONSTRAINT factura_pkey PRIMARY KEY (id_factura),
  CONSTRAINT factura_total_coherente_check CHECK (total_pagar = subtotal + propina),   -- restriccion nueva
  CONSTRAINT factura_id_usuario_fkey FOREIGN KEY (id_usuario)
    REFERENCES public.usuario(id_usuario) ON DELETE RESTRICT,
  CONSTRAINT factura_id_mesa_fkey FOREIGN KEY (id_mesa)
    REFERENCES public.mesa(id_mesa) ON DELETE RESTRICT
);

CREATE TABLE public.detalle_factura (
  id_detalle_factura integer GENERATED BY DEFAULT AS IDENTITY,
  id_factura      integer NOT NULL,
  id_producto     integer NOT NULL,
  cantidad        integer NOT NULL CHECK (cantidad > 0),
  precio_unitario numeric NOT NULL CHECK (precio_unitario >= 0::numeric),
  subtotal        numeric NOT NULL DEFAULT 0 CHECK (subtotal >= 0::numeric),
  CONSTRAINT detalle_factura_pkey PRIMARY KEY (id_detalle_factura),
  CONSTRAINT detalle_factura_subtotal_coherente_check CHECK (subtotal = cantidad * precio_unitario),  -- restriccion nueva
  CONSTRAINT detalle_factura_id_factura_fkey FOREIGN KEY (id_factura)
    REFERENCES public.factura(id_factura) ON DELETE CASCADE,
  CONSTRAINT detalle_factura_id_producto_fkey FOREIGN KEY (id_producto)
    REFERENCES public.producto(id_producto) ON DELETE RESTRICT
);

CREATE TABLE public.turno_caja (
  id_turno_caja       integer GENERATED BY DEFAULT AS IDENTITY,
  id_caja             integer NOT NULL,
  id_usuario_apertura integer NOT NULL,
  id_usuario_cierre   integer,
  fecha_apertura      timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
  fecha_cierre        timestamp without time zone,
  monto_inicial       numeric NOT NULL CHECK (monto_inicial >= 0::numeric),
  monto_final         numeric CHECK (monto_final IS NULL OR monto_final >= 0::numeric),
  estado              character varying NOT NULL DEFAULT 'Abierto',
  CONSTRAINT turno_caja_pkey PRIMARY KEY (id_turno_caja),
  CONSTRAINT turno_caja_estado_check CHECK (estado IN ('Abierto','Cerrado')),
  CONSTRAINT turno_caja_fechas_check CHECK (fecha_cierre IS NULL OR fecha_cierre >= fecha_apertura),
  -- un turno abierto no tiene datos de cierre; uno cerrado los tiene todos
  CONSTRAINT turno_caja_cierre_coherente_check CHECK (
    (estado = 'Abierto' AND fecha_cierre IS NULL AND id_usuario_cierre IS NULL AND monto_final IS NULL)
    OR
    (estado = 'Cerrado' AND fecha_cierre IS NOT NULL AND id_usuario_cierre IS NOT NULL AND monto_final IS NOT NULL)),
  CONSTRAINT turno_caja_id_caja_fkey FOREIGN KEY (id_caja)
    REFERENCES public.caja(id_caja) ON DELETE RESTRICT,
  CONSTRAINT turno_caja_id_usuario_apertura_fkey FOREIGN KEY (id_usuario_apertura)
    REFERENCES public.usuario(id_usuario) ON DELETE RESTRICT,
  CONSTRAINT turno_caja_id_usuario_cierre_fkey FOREIGN KEY (id_usuario_cierre)
    REFERENCES public.usuario(id_usuario) ON DELETE RESTRICT
);

-- Regla de negocio: una caja no puede tener dos turnos abiertos a la vez.
CREATE UNIQUE INDEX uq_turno_abierto_por_caja ON public.turno_caja (id_caja) WHERE estado = 'Abierto';

CREATE TABLE public.historial_caja (
  id_historial_caja integer GENERATED BY DEFAULT AS IDENTITY,
  id_turno_caja     integer NOT NULL,
  id_usuario        integer NOT NULL,
  id_factura        integer,
  metodo_pago       character varying NOT NULL,
  tipo_pago         character varying NOT NULL,
  monto             numeric NOT NULL CHECK (monto >= 0::numeric),
  descripcion       character varying,
  fecha_movimiento  timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT historial_caja_pkey PRIMARY KEY (id_historial_caja),
  CONSTRAINT historial_caja_metodo_check CHECK (metodo_pago IN ('Efectivo','Tarjeta','Transferencia')),
  CONSTRAINT historial_caja_tipo_check CHECK (tipo_pago IN ('Ingreso','Egreso')),
  CONSTRAINT historial_caja_id_turno_caja_fkey FOREIGN KEY (id_turno_caja)
    REFERENCES public.turno_caja(id_turno_caja) ON DELETE RESTRICT,
  CONSTRAINT historial_caja_id_usuario_fkey FOREIGN KEY (id_usuario)
    REFERENCES public.usuario(id_usuario) ON DELETE RESTRICT,
  CONSTRAINT historial_caja_id_factura_fkey FOREIGN KEY (id_factura)
    REFERENCES public.factura(id_factura) ON DELETE RESTRICT
);

CREATE TABLE public.historial_mesa (
  id_historial_mesa integer GENERATED BY DEFAULT AS IDENTITY,
  id_mesa      integer NOT NULL,
  id_comanda   integer,
  id_usuario   integer NOT NULL,
  estado       character varying NOT NULL,
  monto        numeric CHECK (monto IS NULL OR monto >= 0::numeric),
  motivo       character varying,
  fecha_accion timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT historial_mesa_pkey PRIMARY KEY (id_historial_mesa),
  CONSTRAINT historial_mesa_estado_check CHECK (estado IN ('Libre','Ocupada','Reservada','Por pagar')),
  CONSTRAINT historial_mesa_id_mesa_fkey FOREIGN KEY (id_mesa)
    REFERENCES public.mesa(id_mesa) ON DELETE RESTRICT,
  CONSTRAINT historial_mesa_id_comanda_fkey FOREIGN KEY (id_comanda)
    REFERENCES public.comanda(id_comanda) ON DELETE SET NULL,
  CONSTRAINT historial_mesa_id_usuario_fkey FOREIGN KEY (id_usuario)
    REFERENCES public.usuario(id_usuario) ON DELETE RESTRICT
);

COMMIT;
